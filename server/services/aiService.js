import axios from 'axios';

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const safeText = (value) => (typeof value === 'string' ? value.trim() : '');

const buildMockSuggestions = ({ symptoms = [], history = [], vitals = {} }) => {
  const text = [...symptoms, ...history].join(' ').toLowerCase();
  const fever = Number(vitals.temperature) > 38 || /fever|chill/.test(text);
  const lowO2 = Number(vitals.spo2) > 0 && Number(vitals.spo2) < 94;
  const tachy = Number(vitals.heartRate) > 100;
  const results = [];

  if (fever && lowO2) {
    results.push({
      name: 'Lower respiratory infection pattern',
      confidence: 82,
      reasoning: ['Fever pattern detected', 'Oxygen saturation below 94%', 'Pattern warrants prompt clinical review'],
    });
  }

  if (fever) {
    results.push({
      name: 'Acute infectious/inflammatory syndrome',
      confidence: 71,
      reasoning: ['Fever is a contributing feature', 'History and examination are needed for differentiation'],
    });
  }

  if (tachy) {
    results.push({
      name: 'Tachycardia-associated stress response',
      confidence: 63,
      reasoning: ['Heart rate above 100 bpm', 'May be associated with fever, pain, dehydration or other causes'],
    });
  }

  if (!results.length) {
    results.push({
      name: 'Non-specific presentation',
      confidence: 42,
      reasoning: ['Current inputs do not strongly match a single pattern', 'Additional history, examination and tests may be required'],
    });
  }

  return {
    mode: 'mock',
    disclaimer: 'Decision support only — not a substitute for clinical judgment.',
    suggestions: results.slice(0, 3),
    risk: lowO2 && fever ? 'High' : tachy || fever ? 'Medium' : 'Low',
  };
};

const callExternalProvider = async ({ symptoms, history, vitals, message }) => {
  const apiKey = process.env.AI_API_KEY;
  if (!apiKey) return null;

  try {
    const response = await axios.post(
      'https://api.openai.com/v1/chat/completions',
      {
        model: process.env.AI_MODEL || 'gpt-4o-mini',
        temperature: 0.2,
        messages: [
          {
            role: 'system',
            content:
              'You are a clinical decision-support assistant. Provide structured, non-diagnostic guidance only. Do not claim medical certainty. Always include the disclaimer: "Decision support only — not a substitute for clinical judgment."',
          },
          {
            role: 'user',
            content: message || JSON.stringify({ symptoms, history, vitals }),
          },
        ],
      },
      {
        headers: {
          Authorization: `Bearer ${apiKey}`,
          'Content-Type': 'application/json',
        },
      },
    );

    const content = response.data?.choices?.[0]?.message?.content || '';
    return {
      mode: 'provider',
      disclaimer: 'Decision support only — not a substitute for clinical judgment.',
      output: content,
    };
  } catch (error) {
    console.warn('AI provider unavailable; falling back to deterministic mock mode.', error.message);
    return null;
  }
};

export async function diagnose(payload = {}) {
  const { symptoms = [], history = [], vitals = {} } = payload;
  const provider = (process.env.AI_MODE || process.env.AI_PROVIDER || 'mock').toLowerCase();

  if (provider !== 'mock') {
    const external = await callExternalProvider({ symptoms, history, vitals });
    if (external) {
      return {
        ...external,
        suggestions: [
          {
            name: 'Provider-generated clinical context',
            confidence: 78,
            reasoning: [
              'This output was generated by the configured AI provider.',
              'It is a decision-support aid, not a diagnosis or treatment order.',
            ],
          },
        ],
        risk: 'Medium',
      };
    }
  }

  await sleep(900);
  return buildMockSuggestions({ symptoms, history, vitals });
}

export async function chat(message = '') {
  const provider = (process.env.AI_MODE || process.env.AI_PROVIDER || 'mock').toLowerCase();
  const trimmed = safeText(message);

  if (provider !== 'mock' && process.env.AI_API_KEY) {
    const external = await callExternalProvider({ message: trimmed });
    if (external) {
      return {
        reply: external.output || 'I can help structure the question without making a diagnostic claim.',
        disclaimer: external.disclaimer,
      };
    }
  }

  await sleep(650);
  return {
    reply: `I can help structure the clinical question. For “${trimmed.slice(0, 120) || 'this case'}”, review the patient context, vitals, medications and relevant investigations before acting. This demo assistant does not provide autonomous medical advice.`,
    disclaimer: 'Decision support only — not a substitute for clinical judgment.',
  };
}
